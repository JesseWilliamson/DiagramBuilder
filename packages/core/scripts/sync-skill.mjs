#!/usr/bin/env node
// Copy dsviz's Claude skill into another repository, so agents working there
// load the same instructions this library documents:
//
//   npm run sync:skill -- ../GitGoose        (from this checkout)
//
// It copies from the checkout's .claude/skills/dsviz/ (the npm packages do not
// ship the skill). It writes <repo>/.claude/skills/dsviz/, replacing whatever was there, so a
// file removed here disappears there too. The copy is generated: edit the skill
// in DiagramBuilder and sync again, never the copy.
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const from = path.join(root, '.claude', 'skills', 'dsviz');
const target = process.argv[2];
if (!target) {
  console.error('usage: sync-skill <path to the other repository>');
  process.exit(1);
}
if (!existsSync(target)) {
  console.error(`sync-skill: ${target} does not exist`);
  process.exit(1);
}
const to = path.join(path.resolve(target), '.claude', 'skills', 'dsviz');
if (path.resolve(to) === path.resolve(from)) {
  console.error('sync-skill: refusing to copy the skill onto itself');
  process.exit(1);
}
const { version } = JSON.parse(readFileSync(path.join(root, 'packages', 'core', 'package.json'), 'utf8'));
rmSync(to, { recursive: true, force: true });
cpSync(from, to, { recursive: true });
writeFileSync(path.join(to, '.synced-from'), `dsviz ${version}\nGenerated by dsviz's sync-skill: edit the skill in DiagramBuilder, then sync again.\n`);
console.log(`dsviz ${version} skill → ${path.relative(process.cwd(), to) || to}`);
